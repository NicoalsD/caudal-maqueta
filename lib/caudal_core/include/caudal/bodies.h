// JSON bodies for the device protocol, written by hand so the bytes are exact.
// The signature covers these bytes, so they must not be re-serialized after signing.
#ifndef CAUDAL_BODIES_H
#define CAUDAL_BODIES_H

#include <stddef.h>
#include <stdint.h>

namespace caudal {

struct TelemetryPoint {
  char id[37];             // UUID v4 text, generated by the device
  const char* metric;      // LEVEL, BATTERY_V, RSSI or VALVE_POSITION
  int32_t value_centi;     // value times 100, so 2.10 is 210
  int64_t observed_at_s;   // seconds since the epoch, UTC
};

// Writes {"points":[{"id","metric","value","observed_at"},...]} with each value
// as fixed-point text with two decimals. Returns the length, or 0 if `cap` is too small.
size_t build_telemetry_body(const TelemetryPoint* points, size_t n, char* out, size_t cap);

// Writes {"result":"ACKED"|"FAILED","detail":"..."}. Quotes and backslashes in `detail`
// are escaped. Returns the length, or 0 if `cap` is too small.
size_t build_ack_body(bool acked, const char* detail, char* out, size_t cap);

// Writes a value times 100 as fixed-point text: 210 -> "2.10", -5 -> "-0.05".
// Returns the length, or 0 if `cap` is too small.
size_t format_centi(int32_t centi, char* out, size_t cap);

}  // namespace caudal

#endif  // CAUDAL_BODIES_H
